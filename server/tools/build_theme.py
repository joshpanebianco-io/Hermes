def grab(lines: list[str], marker: str) -> str:
    i = next(k for k, line in enumerate(lines) if line.startswith(marker))
    j = next(k for k in range(i, len(lines)) if lines[k].rstrip() == "];")
    return "".join(lines[i : j + 1])


def main() -> None:
    src_path = os.path.join(GEX, "src", "lib", "theme.ts")
    with open(src_path, encoding="utf-8") as f:
        lines = f.read().splitlines(keepends=True)

    hues = grab(lines, "export const HUES")
    presets = grab(lines, "export const PRESETS")
    for slot in DROP:
        presets = re.sub(rf"^\s*{slot}: \"[a-z]+\",\n", "", presets, flags=re.M)

    out = os.path.join(HERE, "src", "lib", "theme.ts")
    with open(out, "w", encoding="utf-8", newline="") as f:
        f.write(HEAD + hues + MID + presets + TAIL)

    n_h = len(re.findall(r'^\s{4}id: "', hues, flags=re.M))
    n_p = re.findall(r'^\s{4}id: "([a-z]+)"', presets, flags=re.M)
    print(f"wrote {out}")
    print(f"  {n_h} hues, {len(n_p)} presets: {', '.join(n_p)}")


if __name__ == "__main__":
    main()

/** The preset this theme exactly matches, if any. */
export function matchPreset(t: ThemeChoice): Preset | undefined {
  const keys = Object.keys(DEFAULT_THEME) as (keyof ThemeChoice)[];
  return PRESETS.find((p) => keys.every((k) => p.theme[k] === t[k]));
}

/**
 * A theme -> the custom properties globals.css reads.
 *
 * ONLY THE TOKENS THIS TERMINAL ACTUALLY DEFINES. GEXYGEN emits about forty;
 * these are every themed token in globals.css. Emitting one it does not define
 * would be a value nothing reads, which is how a stylesheet and a theme quietly
 * stop agreeing.
 */
export function themeVars(t: ThemeChoice): Record<string, string> {
  const call = hue(t.call, "green");
  const put = hue(t.put, "pink");
  const flip = hue(t.flip, "amber");
  const neutral = hue(t.neutral, "white");
  const tabs = hue(t.tabs, "amber");
  const iconA = hue(t.iconA, "green");
  const iconB = hue(t.iconB, "pink");
  const titleA = hue(t.titleA, "green");
  // Solid mode is not a token: the gradient runs between two identical stops,
  // so nothing downstream needs to know a mode exists.
  const titleB = hue(t.titleMode === "solid" ? t.titleA : t.titleB, "pink");
  const sheen = hue(t.sheen, "white");
  const frameA = hue(t.frameA, "green");
  const frameB = hue(t.frameMode === "solid" ? t.frameA : t.frameB, "pink");

  return {
    "--call": call.mark,
    "--put": put.mark,
    "--flip": flip.mark,
    "--spot": neutral.ink,
    "--call-dte": call.dte,
    "--put-dte": put.dte,
    // The FIGURE tier: what Quiet prints a signed number in. Brighter than
    // the mark on purpose, as GEXYGEN's Quiet does, since a figure is text.
    "--call-fig": call.fig,
    "--put-fig": put.fig,
    "--flip-fig": flip.fig,
    "--neon-call": call.neon,
    "--neon-put": put.neon,
    "--neon-flip": flip.neon,
    "--tab-accent": tabs.neon,
    "--icon-a": iconA.neon,
    "--icon-b": iconB.neon,
    "--title-a": titleA.neon,
    "--title-a-lift": titleA.lift,
    "--title-b": titleB.neon,
    "--title-b-lift": titleB.lift,
    "--title-sheen": sheen.lift,
    "--frame-a": frameA.neon,
    "--frame-b": frameB.neon,
  };
}

/** The same, as a React style object for `<html>`. */
export function themeStyle(t: ThemeChoice): React.CSSProperties {
  return themeVars(t) as React.CSSProperties;
}

/**
 * Parse a stored theme, keeping only values this build knows.
 *
 * EVERY FIELD FALLS BACK INDEPENDENTLY, so a cookie written by a later build
 * that adds a slot degrades to the default for that one slot rather than
 * throwing the whole theme away.
 */
export function parseTheme(raw: string | undefined): ThemeChoice {
  if (!raw) return DEFAULT_THEME;
  let v: Record<string, unknown>;
  try {
    v = JSON.parse(decodeURIComponent(raw)) as Record<string, unknown>;
  } catch {
    return DEFAULT_THEME;
  }
  const pick = (k: keyof ThemeChoice): HueId =>
    isHueId(v[k]) ? (v[k] as HueId) : (DEFAULT_THEME[k] as HueId);
  const mode = (k: "titleMode" | "frameMode"): DuoMode =>
    v[k] === "solid" || v[k] === "duo" ? (v[k] as DuoMode) : DEFAULT_THEME[k];
  return {
    call: pick("call"),
    put: pick("put"),
    flip: pick("flip"),
    neutral: pick("neutral"),
    tabs: pick("tabs"),
    iconA: pick("iconA"),
    iconB: pick("iconB"),
    titleMode: mode("titleMode"),
    titleA: pick("titleA"),
    titleB: pick("titleB"),
    sheen: pick("sheen"),
    frameMode: mode("frameMode"),
    frameA: pick("frameA"),
    frameB: pick("frameB"),
  };
}


/**
 * The palette, made switchable — imported wholesale from GEXYGEN.
 *
 * WHY IMPORTED RATHER THAN REINVENTED. GEXYGEN's `lib/theme.ts` is where the
 * work actually happened: seventeen hues, each with eight tiers generated as
 * fixed lightness and chroma targets in OKLCH and clamped into sRGB per tier,
 * every one contrast-checked against the surface #11131a before it was written
 * down. Ink, dteInk and ladInk clear 4.5:1; no offered hue lands within 30
 * degrees of the flip's amber, so a themed wall can never be mistaken for the
 * flip line. None of that is worth doing twice, and doing it twice would mean
 * two palettes that drift.
 *
 * GENERATED by server/tools/build_theme.py. Edit that, not this.
 *
 * EVERY TIER IS A LITERAL HEX, NOT A `color-mix()`. GEXYGEN needs that because
 * it reads tokens with `getComputedStyle().getPropertyValue()` and hands them
 * to a canvas, which would receive an unresolved `color-mix(...)` string and
 * draw nothing. This terminal has no canvas today — but the constraint costs
 * nothing and the sparklines are one refactor from wanting it.
 *
 * WHAT WAS DROPPED ON THE WAY ACROSS: GEXYGEN's `posCall`/`posPut` (its
 * Positioning card, the only place a side hue is drawn at partial strength) and
 * `volCool`/`volMid`/`volHot` (the ATM IV heat ramp). Neither has anything to
 * bind to here.
 *
 * WHAT IS DELIBERATELY NOT THEMED: the five desk hues on the wire. They are
 * identity tags on a 3px rail, they have to stay distinguishable from each
 * other at equal value, and letting a preset recolour them would let a headline
 * rail collide with the up/down palette.
 */

export type HueId =
  | "green" | "pink" | "cyan" | "blue" | "purple" | "red" | "crimson"
  | "orange" | "lime" | "cobalt" | "indium" | "iodine" | "sulphur"
  | "amber" | "white" | "silver" | "slate";

export interface Hue {
  id: HueId;
  name: string;
  /** Chart fills and strokes — the identity value. */
  mark: string;
  /** Body-text tier, >=4.5:1 on --surface. */
  ink: string;
  /** The large figures. */
  fig: string;
  /** Glow and decoration — the brightest tier. */
  neon: string;
  /** Stepped-back variants of the same hue. */
  dte: string;
  dteInk: string;
  /** Heavily desaturated, side-tinted. */
  lad: string;
  ladInk: string;
  /** The near-white sheen stop the wordmark gradient routes through. */
  lift: string;
}

export type DuoMode = "solid" | "duo";

export interface ThemeChoice {
  /* --- data: these hues mean something --- */
  /** Calls, positive gamma, and up. */
  call: HueId;
  /** Puts, negative gamma, and down. */
  put: HueId;
  /** The gamma flip, and anything demanding attention. */
  flip: HueId;
  /** Spot and the figures that carry no side. */
  neutral: HueId;

  /* --- chrome: decoration, and free to be anything --- */
  /** The active tab's underline. */
  tabs: HueId;
  /** The two rings of the mark. */
  iconA: HueId;
  iconB: HueId;
  titleMode: DuoMode;
  titleA: HueId;
  titleB: HueId;
  /** The wordmark's third stop — a hue's `lift` tier, never its neon. */
  sheen: HueId;
  frameMode: DuoMode;
  frameA: HueId;
  frameB: HueId;
}


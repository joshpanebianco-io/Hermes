const BY_ID = new Map(HUES.map((h) => [h.id, h]));

export function isHueId(v: unknown): v is HueId {
  return typeof v === "string" && BY_ID.has(v as HueId);
}

/** A hue by id, falling back rather than throwing — a bad cookie is not fatal. */
export function hue(id: HueId | string | undefined, fallback: HueId): Hue {
  return BY_ID.get(id as HueId) ?? BY_ID.get(fallback)!;
}

